import json
from pathlib import Path
from threading import Lock
from typing import List, Optional

from fastapi import FastAPI, HTTPException, Query
from pydantic import BaseModel

from .query_engine import answer, build_timeline
from paths import TESTING_CONSOLIDATED_FILE


PREDICTIONS_FILE = TESTING_CONSOLIDATED_FILE


class ActivityInterval(BaseModel):
    activity: str
    start_timestamp: float
    end_timestamp: float


class QuestionRequest(BaseModel):
    question: str


class HealthResponse(BaseModel):
    status: str
    prediction_file: str
    interval_count: int


class PredictionQueryEngine:
    def __init__(self, predictions_file: Path):
        self.predictions_file = predictions_file
        self._predictions: List[ActivityInterval] = []
        self._modified_time = 0.0
        self._lock = Lock()
        self.reload_if_needed()

    def reload_if_needed(self) -> None:
        if not self.predictions_file.exists():
            raise FileNotFoundError(f"Predictions file not found: {self.predictions_file}")

        modified_time = self.predictions_file.stat().st_mtime
        if modified_time == self._modified_time:
            return

        with self._lock:
            if modified_time == self._modified_time:
                return

            with self.predictions_file.open("r", encoding="utf-8") as file:
                raw_predictions = json.load(file)

            predictions = [ActivityInterval.model_validate(item) for item in raw_predictions]
            predictions.sort(key=lambda item: item.start_timestamp)
            self._predictions = predictions
            self._modified_time = modified_time

    def all(self) -> List[ActivityInterval]:
        self.reload_if_needed()
        return list(self._predictions)

    def query(
        self,
        activity: Optional[str] = None,
        start_timestamp: Optional[float] = None,
        end_timestamp: Optional[float] = None,
    ) -> List[ActivityInterval]:
        predictions = self.all()

        if activity is not None:
            predictions = [
                item
                for item in predictions
                if item.activity.casefold() == activity.casefold()
            ]

        if start_timestamp is not None:
            predictions = [
                item
                for item in predictions
                if item.end_timestamp >= start_timestamp
            ]

        if end_timestamp is not None:
            predictions = [
                item
                for item in predictions
                if item.start_timestamp <= end_timestamp
            ]

        return predictions

    def activity_at(self, timestamp: float) -> List[ActivityInterval]:
        return [
            item
            for item in self.all()
            if item.start_timestamp <= timestamp <= item.end_timestamp
        ]


app = FastAPI(
    title="Activity Prediction Query API",
    description="Query consolidated activity predictions generated by prediction.py.",
    version="1.0.0",
)
engine = PredictionQueryEngine(PREDICTIONS_FILE)


@app.get("/health", response_model=HealthResponse, tags=["System"])
def health() -> HealthResponse:
    engine.reload_if_needed()
    return HealthResponse(
        status="ok",
        prediction_file=str(PREDICTIONS_FILE),
        interval_count=len(engine.all()),
    )


@app.get("/activities", response_model=List[str], tags=["Predictions"])
def activities():
    return sorted({item.activity for item in engine.all()})


@app.get("/predictions", response_model=List[ActivityInterval], tags=["Predictions"])
def predictions(
    activity: Optional[str] = Query(default=None),
    start_timestamp: Optional[float] = Query(default=None, ge=0),
    end_timestamp: Optional[float] = Query(default=None, ge=0),
):
    if (
        start_timestamp is not None
        and end_timestamp is not None
        and start_timestamp > end_timestamp
    ):
        raise HTTPException(
            status_code=400,
            detail="start_timestamp must be less than or equal to end_timestamp",
        )

    return engine.query(activity, start_timestamp, end_timestamp)


@app.get("/predictions/at", response_model=List[ActivityInterval], tags=["Predictions"])
def predictions_at(
    timestamp: float = Query(..., ge=0),
):
    return engine.activity_at(timestamp)


@app.post("/query", tags=["Question Engine"])
def query_prediction(request: QuestionRequest):
    if not request.question.strip():
        raise HTTPException(status_code=400, detail="question must not be empty")

    timeline = build_timeline([item.model_dump() for item in engine.all()])
    return answer(request.question, timeline)


if __name__ == "__main__":
    import uvicorn

    uvicorn.run("server.prediction_api:app", host="127.0.0.1", port=8000, reload=False)
